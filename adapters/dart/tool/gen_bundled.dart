// Regenerates lib/src/bundled_toolkits.dart from toolkits/*.sdl.
// Run from adapters/dart: dart run tool/gen_bundled.dart
import 'dart:io';

void main() {
  final files = Directory('toolkits').listSync().whereType<File>().where((f) => f.path.endsWith('.sdl')).toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  final b = StringBuffer('// GENERATED by tool/gen_bundled.dart from toolkits/*.sdl. Do not edit.\n\n'
      '/// Bundled toolkit manifests keyed by file name.\nconst bundledToolkits = <String, String>{\n');
  for (final f in files) {
    final name = f.uri.pathSegments.last;
    b.writeln("  '$name': r'''${f.readAsStringSync()}''',");
  }
  b.writeln('};');
  File('lib/src/bundled_toolkits.dart').writeAsStringSync(b.toString());
}
